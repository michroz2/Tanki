/**
 * @file motor_control.h
 * @version 1.3
 * @brief Модуль управления ходовыми двигателями танка (драйверы BTS7960).
 * * v1.2: Добавлена функция updateMotorInertia() для линейного ограничения ускорения (Slew Rate).
 */

 #pragma once
 #include <Arduino.h>
 
 /**
  * @brief Инициализация ШИМ-каналов и привязка пинов. 
  * Устанавливает начальное безопасное состояние (остановка).
  */
 void initMotors();
 
 /**
  * @brief Установка ЦЕЛЕВОЙ скорости и направления вращения гусениц.
  * @param leftSpeed Скорость левой гусеницы (от -255 до 255). 
  * @param rightSpeed Скорость правой гусеницы (от -255 до 255).
  */
 void setMotorSpeeds(int leftSpeed, int rightSpeed);
 
 /**
  * @brief Неблокирующий расчет инерционного изменения скорости моторов.
  * Должен вызываться на каждом проходе основного цикла loop().
  * @param vrbRaw Значение канала VRB (1000..2000 мкс), определяющее время разгона/торможения.
  */
 void updateMotorInertia(int vrbRaw);